package com.applypilot.backend.resume.parsing;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;
import java.util.*;

/** The schema subset used here is deliberately small and also validated locally (no JSON coercion). */
public final class ResumeJsonSchema {
    private static final ObjectMapper JSON = new ObjectMapper();
    private ResumeJsonSchema() {}
    public static JsonNode schema() {
        var scalar = Map.of("type", List.of("string", "null"), "maxLength", 1000);
        var text = Map.of("type", List.of("string", "null"), "maxLength", 200000);
        var bullets = Map.of("type", "array", "maxItems", 500, "items", Map.of("type", "string", "maxLength", 10000));
        var education = fields(scalar, "institution", "degree", "fieldOfStudy", "startDate", "endDate", "location");
        education.put("originalText", text);
        var experience = fields(scalar, "company", "jobTitle", "jobTittle", "startDate", "endDate", "location");
        experience.put("responsibilities", bullets); experience.put("originalText", text);
        var project = fields(scalar, "name");
        project.put("technologies", bullets); project.put("description", bullets); project.put("originalText", text);
        var root = fields(scalar, "fullName", "email", "phone", "location");
        root.put("summary", text); root.put("skills", bullets);
        root.put("education", array(object(education))); root.put("experience", array(object(experience)));
        root.put("projects", array(object(project)));
        // Source annotations are supplied by the server, never generated by an LLM.
        return JSON.valueToTree(object(root));
    }
    private static Map<String,Object> fields(Object schema, String... names) {
        var result = new LinkedHashMap<String,Object>();
        for (String name : names) result.put(name, schema);
        return result;
    }
    private static Object object(Map<String,Object> properties) {
        return Map.of("type","object","properties",properties,"required",new ArrayList<>(properties.keySet()),"additionalProperties",false);
    }
    private static Object array(Object item) { return Map.of("type","array","maxItems",100,"items",item); }
    public static void validate(JsonNode value) { validate(value, schema()); }
    private static void validate(JsonNode value, JsonNode schema) {
        String type = value == null ? "missing" : value.isNull() ? "null" : value.isObject() ? "object"
                : value.isArray() ? "array" : value.isTextual() ? "string" : "unsupported";
        JsonNode expected = schema.get("type");
        boolean matches = expected.isArray() ? java.util.stream.StreamSupport.stream(expected.spliterator(), false)
                .anyMatch(t -> t.asText().equals(type)) : expected.asText().equals(type);
        if (!matches) invalid();
        if (type.equals("object")) {
            JsonNode properties = schema.get("properties");
            for (JsonNode required : schema.get("required")) if (!value.has(required.asText())) invalid();
            var names = value.fieldNames();
            while (names.hasNext()) { String name = names.next(); if (!properties.has(name)) invalid(); validate(value.get(name), properties.get(name)); }
        } else if (type.equals("array")) {
            if (value.size() > schema.path("maxItems").asInt()) invalid();
            for (JsonNode item : value) validate(item, schema.get("items"));
        } else if (type.equals("string") && value.textValue().length() > schema.path("maxLength").asInt()) invalid();
    }
    private static void invalid() { throw new ResumeParsingException("AI returned an invalid profile. Retry extraction or enter your profile manually."); }
}
